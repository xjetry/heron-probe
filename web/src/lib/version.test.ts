import { describe, expect, it } from "vitest";
import { lagsHub } from "./version";

describe("lagsHub 按 semver 2.0 优先级比较", () => {
  it.each([
    ["v1.9.0", "v1.10.0"],
    ["v0.9.9", "v1.0.0"],
    ["v2.0.0", "v10.0.0"],
    ["v1.1.0-rc.1", "v1.1.1"],
    // 同一 MAJOR.MINOR.PATCH 下预发布低于正式版。
    ["v1.1.0-rc.1", "v1.1.0"],
    ["v1.1.0-alpha", "v1.1.0-beta"],
    ["v1.1.0-alpha.1", "v1.1.0-alpha.2"],
    // 纯数字标识符按数值比，不按字符串比。
    ["v1.1.0-alpha.2", "v1.1.0-alpha.10"],
    ["v1.1.0-alpha.99999999999999999999", "v1.1.0-alpha.100000000000000000000"],
    // 前缀全等时段数多者更高。
    ["v1.1.0-alpha", "v1.1.0-alpha.1"],
    // 数字标识符低于字母数字标识符。
    ["v1.1.0-alpha.1", "v1.1.0-alpha.beta"],
    // 含字母或连字符的标识符按 ASCII 比。
    ["v1.1.0-a-b", "v1.1.0-a-c"],
    ["v1.1.0-RC", "v1.1.0-rc"],
    // 构建元数据能解析且不参与比较。
    ["v1.2.3+build.5", "v1.2.4"],
    ["v1.1.0-rc.1+b9", "v1.1.0+b1"],
  ])("%s 落后于 %s", (agent, hub) => {
    expect(lagsHub(agent, hub)).toBe(true);
  });

  it.each([
    ["v1.1.0", "v1.1.0"],
    ["v1.2.0", "v1.1.0"],
    // hub 为预发布、agent 为对应的正式版：agent 更高。
    ["v1.1.0", "v1.1.0-rc.1"],
    ["v1.1.0-beta", "v1.1.0-alpha"],
    ["v1.1.0-alpha.10", "v1.1.0-alpha.2"],
    ["v1.1.0-alpha.1", "v1.1.0-alpha"],
    // 只差构建元数据视为同一版本。
    ["v1.1.0+b1", "v1.1.0+b2"],
    ["v1.1.0+b2", "v1.1.0+b1"],
  ])("%s 不落后于 %s", (agent, hub) => {
    expect(lagsHub(agent, hub)).toBe(false);
  });

  // 任一方不是合法的正式或预发布版本号就没有可比的次序，不标。
  it.each([
    ["dev", "v1.1.0"],
    ["v1.0.0", "dev"],
    ["v1.0.0", ""],
    [undefined, "v1.1.0"],
    ["", "v1.1.0"],
    ["1.0.0", "v1.1.0"],
    ["v1.0", "v1.1.0"],
    ["v01.0.0", "v1.1.0"],
    // 前导 0 不合法：宽松解析会把下面两对判成落后。
    ["v1.0.0", "v01.1.0"],
    ["v0.9.09", "v0.9.10"],
    ["v1.1.0-alpha.1", "v1.1.0-alpha.01"],
    ["v1.0.0-", "v1.1.0"],
    ["v1.0.0-01", "v1.1.0"],
    ["v1.0.0-a..b", "v1.1.0"],
    ["v1.0.0+", "v1.1.0"],
    ["v1.0.0+a_b", "v1.1.0"],
    ["v1.0.0 ", "v1.1.0"],
  ])("%s 对 %s 解析失败不标", (agent, hub) => {
    expect(lagsHub(agent, hub)).toBe(false);
  });
});
